import { existsSync, mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const HEADER = "// GENERATED by scripts/lib/registry.ts — do not edit";

/** Source of src/videos.generated.ts for the given video slugs. */
export function renderRegistry(slugs: string[]): string {
  const sorted = [...slugs].sort();
  if (sorted.length === 0) {
    return [
      HEADER,
      'import type { RegisteredVideo } from "./fondasi/video";',
      "",
      "export const VIDEOS: RegisteredVideo[] = [];",
      "",
    ].join("\n");
  }
  const imports = sorted.flatMap((slug, i) => [
    `import timeline_${i} from "../videos/${slug}/timeline.json";`,
    `import * as scenes_${i} from "../videos/${slug}/Scenes";`,
  ]);
  const entries = sorted.map((slug, i) =>
    [
      "  {",
      `    slug: ${JSON.stringify(slug)},`,
      `    timeline: TimelineSchema.parse(timeline_${i}),`,
      `    Scenes: scenes_${i}.Scenes,`,
      `    background: (scenes_${i} as { background?: "light" | "dark" }).background ?? "light",`,
      "  },",
    ].join("\n"),
  );
  return [
    HEADER,
    'import { TimelineSchema } from "./fondasi/schema";',
    'import type { RegisteredVideo } from "./fondasi/video";',
    ...imports,
    "",
    "export const VIDEOS: RegisteredVideo[] = [",
    ...entries,
    "];",
    "",
  ].join("\n");
}

/** Slugs of every videos/<slug>/ folder that has a timeline.json. */
export function registeredSlugs(root: string): string[] {
  const videos = join(root, "videos");
  if (!existsSync(videos)) return [];
  return readdirSync(videos, { withFileTypes: true })
    .filter((d) => d.isDirectory() && existsSync(join(videos, d.name, "timeline.json")))
    .map((d) => d.name);
}

/** Regenerates <root>/src/videos.generated.ts. */
export function writeRegistry(root: string): void {
  mkdirSync(join(root, "src"), { recursive: true });
  writeFileSync(join(root, "src", "videos.generated.ts"), renderRegistry(registeredSlugs(root)));
}
