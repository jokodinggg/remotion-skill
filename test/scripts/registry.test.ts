import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { renderRegistry, writeRegistry } from "../../scripts/lib/registry";

describe("renderRegistry", () => {
  it("sorts slugs and imports timeline + scenes per slug", () => {
    const out = renderRegistry(["b", "a"]);
    expect(out.startsWith("// GENERATED by scripts/lib/registry.ts — do not edit")).toBe(true);
    expect(out).toContain('import { TimelineSchema } from "./fondasi/schema"');
    expect(out).toContain('import type { RegisteredVideo } from "./fondasi/video"');
    expect(out).toContain('import timeline_0 from "../videos/a/timeline.json"');
    expect(out).toContain('import * as scenes_0 from "../videos/a/Scenes"');
    expect(out).toContain('import * as scenes_1 from "../videos/b/Scenes"');
    expect(out.indexOf('slug: "a"')).toBeLessThan(out.indexOf('slug: "b"'));
    expect(out).toContain("timeline: TimelineSchema.parse(timeline_0)");
    expect(out).toContain("Scenes: scenes_0.Scenes");
    expect(out).toContain(
      'background: (scenes_0 as { background?: "light" | "dark" }).background ?? "light"',
    );
  });

  it("emits an empty list with no slugs", () => {
    const out = renderRegistry([]);
    expect(out).toContain("export const VIDEOS: RegisteredVideo[] = [];");
    expect(out).not.toContain("TimelineSchema");
  });
});

describe("writeRegistry", () => {
  it("registers only folders that have timeline.json", () => {
    const root = mkdtempSync(join(tmpdir(), "registry-"));
    mkdirSync(join(root, "videos", "with"), { recursive: true });
    mkdirSync(join(root, "videos", "without"), { recursive: true });
    writeFileSync(join(root, "videos", "with", "timeline.json"), "{}");
    writeRegistry(root);
    const out = readFileSync(join(root, "src", "videos.generated.ts"), "utf8");
    expect(out).toContain('"../videos/with/timeline.json"');
    expect(out).not.toContain("without");
  });

  it("writes an empty registry when videos/ is missing", () => {
    const root = mkdtempSync(join(tmpdir(), "registry-"));
    writeRegistry(root);
    const out = readFileSync(join(root, "src", "videos.generated.ts"), "utf8");
    expect(out).toContain("export const VIDEOS: RegisteredVideo[] = [];");
  });
});
